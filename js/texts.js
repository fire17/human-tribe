// User-facing texts that matter most for dignity. Kept in one place so they can be translated
// (Arabic, Russian, Amharic, Tigrinya, English) and reviewed by a social worker and a lawyer before
// field use. Impersonal Hebrew phrasing on purpose: no gendered slashes, so it reads aloud naturally.
//
// Privacy Protection Law §11 (he.wikisource, checked 2026-10-03): a request for personal data for a
// database must say whether answering is voluntary (1), the purpose (2), the controller's identity and
// contact details (2א), who receives it (3), and the right to see and correct it (4).

// The controller (§11(2א)). Official name only, never a nickname. The project phone is not decided yet:
// fill it before field use (README, open decisions).
export const CONTROLLER = { name: 'תמר בר זכאי', org: 'השבט האנושי', phone: '' };

export function consentParas(name) {
  const n = String(name || '').trim();
  const contact = CONTROLLER.phone ? `טלפון: ${CONTROLLER.phone}.` : 'את פרטי הקשר אפשר לבקש ממי שרושם.';
  return [
    { h: 'לפני שמתחילים', p: `${n ? `שלום ${n}. ` : 'שלום. '}לפני שמתחילים, נסביר בדיוק מה קורה עם מה שמספרים לנו. זה לוקח דקה.` },
    { h: 'מה נשמר', p: 'השם או הכינוי שנבחר, ומה שבוחרים לספר: הסיפור, המשאלות ומה חסר עכשיו. רק מה שצריך כדי לעזור. לא שואלים מספר תעודת זהות.' },
    { h: 'איפה זה נשמר', p: 'רק בטלפון הזה. זה לא עולה לאינטרנט — חוץ מתמלול קולי, ורק אם מסכימים לו בנפרד. אין לנו שרת, אין פרסומות ואין מעקב.' },
    { h: 'מי רואה', p: 'רק מי שמחזיק את הטלפון הזה.' },
    { h: 'שיתוף', p: 'שום דבר לא עובר לעובדת סוציאלית, לעמותה או לעורך דין בלי הסכמה, ולכל גורם שואלים בנפרד: למי, ומה בדיוק נספר לו. אפשר להסכים עכשיו, אחר כך, או אף פעם.' },
    { h: 'מי אחראי', p: `האחראי על המידע: ${CONTROLLER.name}, ${CONTROLLER.org}. ${contact} המטרה: לעזור למצוא מחסה, זכויות ועזרה.` },
    { h: 'גבול אחד', p: 'אם יש סכנת חיים מיידית, או פגיעה בילד או באדם שלא יכול לדאוג לעצמו בידי מי שאחראי עליו — נעביר את זה לגורם מוסמך גם בלי הסכמה. זו חובה לפי החוק.' },
    { h: 'מחיקה', p: 'אפשר לבקש לראות את כל מה שנשמר, לתקן, או למחוק הכל — בכל רגע, בלי להסביר למה. מה שכבר נמסר לגורם בהסכמה — נבקש ממנו למחוק, אבל את זה אי אפשר להבטיח.' },
    { h: 'לא חייבים', p: 'לא חייבים לענות על שום שאלה. מספרים רק מה שנוח, ואפשר לעצור בכל רגע.' },
  ];
}

